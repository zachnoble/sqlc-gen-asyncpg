async def test_prepared(conn: asyncpg.Connection, dsn: str) -> None:
    from cases.options.gen_prepared import batch, db, models, query

    q = await db.Queries.prepare(conn)
    assert len(q._stmts) == 14
    await seed(q, models, query)
    assert [u.user_name for u in await q.list_users()] == ["ann", "bob", "cid"]
    assert await q.get_user(2) is not None
    assert await q.set_status(query.SetStatusParams(user_id=1, status=models.Status.CLOSED)) == 1
    assert await q.touch([1, 2, 3]) == "UPDATE 3"
    await q.batch_status([batch.BatchStatusParams(user_id=2, status=models.Status.CLOSED)])
    assert await q.batch_names([models.Status.CLOSED]) == [["ann", "bob"]]
    assert await q.batch_get([3]) == [batch.BatchGetRow(user_id=3, user_name="cid")]
    assert await q.copy_users([query.CopyUsersParams(user_name="z", email_addr=None, status=models.Status.OPEN)]) == 1
    stmt = q._stmts[query._GET_USER]
    assert (await stmt.fetchrow(1))["user_name"] == "ann"
    # same connection keeps statements, another drops them
    async with conn.transaction():
        qt = q.with_tx(conn)
        assert qt._stmts is q._stmts
        await qt.delete_all()
        assert await qt.count_users() == 0
    other = await asyncpg.connect(dsn)
    try:
        q2 = q.with_tx(other)
        assert q2._stmts == {}
        assert await q2.count_users() == 0
    finally:
        await other.close()
    q.close()
    assert q._stmts == {}
    assert await q.count_users() == 0  # falls back to unprepared execution



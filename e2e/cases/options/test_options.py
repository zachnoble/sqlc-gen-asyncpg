@pytest.mark.parametrize(
    ("variant", "keys"),
    [
        ("gen_default", ["user_id", "user_name", "email_addr", "status"]),
        ("gen_json_none", ["user_id", "user_name", "email_addr", "status"]),
        ("gen_json_snake", ["user_id", "user_name", "email_addr", "status"]),
        ("gen_json_camel", ["userId", "userName", "emailAddr", "status"]),
        ("gen_json_camel_id", ["userID", "userName", "emailAddr", "status"]),
        ("gen_json_pascal", ["UserID", "UserName", "EmailAddr", "Status"]),
    ],
)
async def test_json_names(conn: asyncpg.Connection, variant: str, keys: list[str]) -> None:
    db, models, query = mod(variant, "db"), mod(variant, "models"), mod(variant, "query")
    q = db.Queries(conn)
    u = await q.create_user(query.CreateUserParams(user_name="a", email_addr=None, status=models.Status.OPEN))
    encoded = msgspec.json.decode(msgspec.json.encode(u))
    assert list(encoded) == keys
    assert encoded[keys[-1]] == "open"
    assert msgspec.json.decode(msgspec.json.encode(u), type=models.User) == u
    p = msgspec.convert(dict(zip(["user_name", "email_addr", "status"], ["n", None, "closed"], strict=True)), query.CreateUserParams) if variant in ("gen_default", "gen_json_none", "gen_json_snake") else None
    if p is not None:
        assert p.status is models.Status.CLOSED
    found = query.FindUsersRow(user_id=1, user_name="x")
    assert list(msgspec.json.decode(msgspec.json.encode(found))) == keys[:2]



async def test_rename(conn: asyncpg.Connection) -> None:
    from cases.options.gen_rename import models, query

    assert hasattr(models, "Account") and not hasattr(models, "User")
    assert hasattr(models, "State") and not hasattr(models, "Status")
    assert models.Account.__struct_fields__ == ("user_id", "login", "email", "State")
    assert query.CreateUserParams.__struct_fields__ == ("login", "email", "State")
    a = await query.create_user(conn, query.CreateUserParams(login="x", email="e", State=models.State.CLOSED))
    assert a == models.Account(user_id=1, login="x", email="e", State=models.State.CLOSED)
    # field named like its enum class (PEP 649)
    hints = typing.get_type_hints(models.Account)
    assert hints["State"] is models.State
    assert msgspec.convert({"user_id": 1, "login": "x", "email": None, "State": "open"}, models.Account).State is models.State.OPEN



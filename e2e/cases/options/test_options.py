def mod(variant: str, name: str) -> Any:
    return importlib.import_module(f"cases.options.{variant}.{name}")


async def seed(conn: Any, models: Any, query: Any, *, limit: int = 1) -> None:
    """Insert 3 users."""
    for name, email in [("ann", "a@x"), ("bob", None), ("cid", "c@x")]:
        if limit >= 3:
            await query.create_user(conn, name, email, models.Status.OPEN)
        else:
            await query.create_user(conn, query.CreateUserParams(user_name=name, email_addr=email, status=models.Status.OPEN))


async def test_default_all_commands(conn: asyncpg.Connection) -> None:
    from cases.options.gen_default import batch, copyfrom, models, query

    await seed(conn, models, query)
    users = await query.list_users(conn)
    check_return(query.list_users, users)
    assert [u.user_name for u in users] == ["ann", "bob", "cid"]
    assert await query.get_user(conn, users[0].user_id) == users[0]
    assert await query.count_users(conn) == 3
    assert await query.set_status(conn, query.SetStatusParams(user_id=1, status=models.Status.IN_PROGRESS)) == 1
    assert await query.set_status(conn, query.SetStatusParams(user_id=99, status=models.Status.CLOSED)) == 0
    assert await query.touch(conn, [1, 2]) == "UPDATE 2"
    found = await query.find_users(
        conn, query.FindUsersParams(pattern="%", status=models.Status.OPEN, min_id=0, max_id=100, lim=10)
    )
    assert [r.user_name for r in found] == ["bob", "cid"]
    assert await query.create_user_two(conn, query.CreateUserTwoParams(user_name="d", email_addr=None)) == 4
    assert await copyfrom.copy_users(conn, [query.CopyUsersParams(user_name="e", email_addr=None, status=models.Status.CLOSED)]) == 1
    await batch.batch_status(conn, [batch.BatchStatusParams(user_id=5, status=models.Status.OPEN)])
    assert await batch.batch_get(conn, [5, 6]) == [batch.BatchGetRow(user_id=5, user_name="e"), None]
    assert await batch.batch_names(conn, [models.Status.OPEN, models.Status.CLOSED]) == [["bob", "cid", "d", "e"], []]
    await query.delete_all(conn)
    assert await query.count_users(conn) == 0
    assert await query.get_person(conn, 1) is None


async def test_pool_and_transactions(conn: asyncpg.Connection, pool: asyncpg.Pool) -> None:
    from cases.options.gen_default import batch, models, query

    await query.create_user(conn, query.CreateUserParams(user_name="a", email_addr=None, status=models.Status.OPEN))
    assert [u.user_name for u in await query.list_users(pool)] == ["a"]
    async with conn.transaction():
        await query.delete_all(conn)
        assert await query.count_users(conn) == 0
        assert await query.count_users(pool) == 1  # not committed yet
    assert await query.count_users(pool) == 0
    assert await batch.batch_get(pool, [1]) == [None]



async def seed(q: Any, models: Any, query: Any, *, limit: int = 1) -> None:
    """Insert 3 users."""
    for name, email in [("ann", "a@x"), ("bob", None), ("cid", "c@x")]:
        if limit >= 3:
            await q.create_user(name, email, models.Status.OPEN)
        else:
            await q.create_user(query.CreateUserParams(user_name=name, email_addr=email, status=models.Status.OPEN))


async def test_default_all_commands(conn: asyncpg.Connection) -> None:
    from cases.options.gen_default import batch, db, models, query

    q = db.Queries(conn)
    await seed(q, models, query)
    users = await q.list_users()
    check_return(q.list_users, users)
    assert [u.user_name for u in users] == ["ann", "bob", "cid"]
    assert await q.get_user(users[0].user_id) == users[0]
    assert await q.count_users() == 3
    assert await q.set_status(query.SetStatusParams(user_id=1, status=models.Status.IN_PROGRESS)) == 1
    assert await q.set_status(query.SetStatusParams(user_id=99, status=models.Status.CLOSED)) == 0
    assert await q.touch([1, 2]) == "UPDATE 2"
    found = await q.find_users(
        query.FindUsersParams(pattern="%", status=models.Status.OPEN, min_id=0, max_id=100, lim=10)
    )
    assert [r.user_name for r in found] == ["bob", "cid"]
    assert await q.create_user_two(query.CreateUserTwoParams(user_name="d", email_addr=None)) == 4
    assert await q.copy_users([query.CopyUsersParams(user_name="e", email_addr=None, status=models.Status.CLOSED)]) == 1
    await q.batch_status([batch.BatchStatusParams(user_id=5, status=models.Status.OPEN)])
    assert await q.batch_get([5, 6]) == [batch.BatchGetRow(user_id=5, user_name="e"), None]
    assert await q.batch_names([models.Status.OPEN, models.Status.CLOSED]) == [["bob", "cid", "d", "e"], []]
    await q.delete_all()
    assert await q.count_users() == 0
    assert await q.get_person(1) is None



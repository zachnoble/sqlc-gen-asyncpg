async def test_dbarg(conn: asyncpg.Connection, pool: asyncpg.Pool) -> None:
    from cases.options.gen_dbarg import db, models, query, querier

    q = db.Queries()
    assert not hasattr(q, "with_tx")
    assert list(inspect.signature(db.Queries.get_user).parameters) == ["self", "conn", "user_id"]
    await q.create_user(conn, query.CreateUserParams(user_name="a", email_addr=None, status=models.Status.OPEN))
    assert [u.user_name for u in await q.list_users(conn)] == ["a"]
    assert [u.user_name for u in await q.list_users(pool)] == ["a"]
    async with conn.transaction():
        await q.delete_all(conn)
        assert await q.count_users(conn) == 0
        assert await q.count_users(pool) == 1  # not committed yet
    assert await q.count_users(pool) == 0
    assert await q.copy_users(conn, [query.CopyUsersParams(user_name="b", email_addr="e", status=models.Status.OPEN)]) == 1
    assert await q.batch_get(pool, [1, 2]) == [None, mod("gen_dbarg", "batch").BatchGetRow(user_id=2, user_name="b")]
    qi: querier.Querier = q
    assert await qi.count_users(conn) == 1



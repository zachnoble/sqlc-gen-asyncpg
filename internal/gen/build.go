package gen

import (
	"fmt"
	"path"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/sqlc-dev/plugin-sdk-go/plugin"
)

type EnumMember struct {
	Name  string
	Value string
}

type Enum struct {
	Name    string
	Comment string
	Members []EnumMember
	used    bool
}

type Field struct {
	Name     string // python attribute
	DBName   string // database column name (used by :copyfrom)
	JSONName string // msgspec encoded name
	Type     fieldType
	Comment  string
	Column   *plugin.Column
	Embed    *Struct // set for sqlc.embed fields
}

type Struct struct {
	Name    string
	Table   *plugin.Identifier
	Comment string
	Fields  []Field
	IsModel bool
	used    bool
}

const (
	argNone = iota
	argSingle
	argFields // multiple individual parameters
	argStruct // a single Params struct parameter
)

const (
	retNone = iota
	retScalar
	retStruct
)

type Query struct {
	Cmd      string
	Name     string // sqlc query name
	Method   string // python function name
	Const    string // SQL constant name
	SQL      string
	Source   string // query file name
	Module   string // python module the query lives in
	Comments []string

	ArgKind   int
	ArgFields []Field // unique parameter fields
	ArgStruct *Struct // Params struct (argStruct, or batch/copyfrom with several params)
	ArgOrder  []int   // for $1..$N: index into ArgFields
	EmitArg   bool    // whether ArgStruct is generated by this query

	RetKind   int
	RetScalar fieldType
	RetStruct *Struct
	EmitRet   bool

	Table *plugin.Identifier
	// CopyFallback: a column type has no binary COPY encoder in asyncpg, so
	// executemany is used.
	CopyFallback bool
}

// hasMethod reports whether a Python function is generated for the query.
func (q *Query) hasMethod() bool {
	return q.Cmd != ":execlastid"
}

func (q *Query) isBatch() bool {
	return strings.HasPrefix(q.Cmd, ":batch")
}

type generator struct {
	req           *plugin.GenerateRequest
	opts          *Options
	defaultSchema string
	enums         []*Enum
	enumByKey     map[string]*Enum
	models        []*Struct
	queries       []*Query
	lay           *layout
}

func (g *generator) buildEnums() {
	g.enumByKey = map[string]*Enum{}
	for _, schema := range g.req.Catalog.GetSchemas() {
		if schema.Name == "pg_catalog" || schema.Name == "information_schema" {
			continue
		}
		for _, e := range schema.Enums {
			name := e.Name
			if schema.Name != g.defaultSchema {
				name = schema.Name + "_" + e.Name
			}
			en := &Enum{Name: g.className(name), Comment: e.Comment}
			seen := uniquer{}
			for i, v := range e.Vals {
				m := enumMemberName(v)
				if !validEnumMember(m) || seen.has(m) {
					m = fmt.Sprintf("VALUE_%d", i)
				}
				m = seen.take(m)
				en.Members = append(en.Members, EnumMember{Name: m, Value: v})
			}
			g.enums = append(g.enums, en)
			g.enumByKey[schema.Name+"."+e.Name] = en
		}
	}
	sort.SliceStable(g.enums, func(i, j int) bool { return g.enums[i].Name < g.enums[j].Name })
}

func (g *generator) buildModels() {
	for _, schema := range g.req.Catalog.GetSchemas() {
		if schema.Name == "pg_catalog" || schema.Name == "information_schema" {
			continue
		}
		for _, table := range schema.Tables {
			name := table.Rel.Name
			if schema.Name != g.defaultSchema {
				name = schema.Name + "_" + table.Rel.Name
			}
			if !g.opts.EmitExactTableNames {
				name = singular(name, g.opts.InflectionExcludeTableNames)
			}
			s := &Struct{
				Name:    g.className(name),
				Table:   &plugin.Identifier{Schema: schema.Name, Name: table.Rel.Name},
				Comment: table.Comment,
				IsModel: true,
			}
			names := uniquer{}
			for _, c := range table.Columns {
				s.Fields = append(s.Fields, Field{
					Name:     names.take(g.fieldName(c.Name)),
					DBName:   c.Name,
					JSONName: g.jsonName(c.Name),
					Type:     g.columnType(c),
					Comment:  c.Comment,
					Column:   c,
				})
			}
			g.models = append(g.models, s)
		}
	}
	sort.SliceStable(g.models, func(i, j int) bool { return g.models[i].Name < g.models[j].Name })
}

func columnName(c *plugin.Column, pos int) string {
	if c.Name != "" {
		return c.Name
	}
	return fmt.Sprintf("column_%d", pos+1)
}

func paramName(p *plugin.Parameter) string {
	if p.Column.GetName() != "" {
		return p.Column.Name
	}
	return fmt.Sprintf("dollar_%d", p.Number)
}

func (g *generator) findModel(id *plugin.Identifier) *Struct {
	if id == nil {
		return nil
	}
	schema := id.Schema
	if schema == "" {
		schema = g.defaultSchema
	}
	for _, s := range g.models {
		if id.Catalog == s.Table.Catalog && id.Name == s.Table.Name && schema == s.Table.Schema {
			return s
		}
	}
	return nil
}

func sameTable(tableID, f *plugin.Identifier, defaultSchema string) bool {
	if tableID == nil {
		return false
	}
	schema := tableID.Schema
	if schema == "" {
		schema = defaultSchema
	}
	return tableID.Catalog == f.Catalog && schema == f.Schema && tableID.Name == f.Name
}

// reservedFuncs are module-level names the generated code relies on; a query
// function with one of these names gets a trailing underscore.
var reservedFuncs = map[string]bool{
	"typing": true, "msgspec": true, "asyncpg": true, "collections": true, "contextlib": true,
	"datetime": true, "decimal": true, "uuid": true, "ipaddress": true, "enum": true, "models": true,
	"list": true, "dict": true, "tuple": true, "int": true, "str": true, "float": true, "bool": true,
	"bytes": true, "len": true, "isinstance": true, "type": true, "object": true, "Exception": true,
}

var validCmds = map[string]bool{
	":one": true, ":many": true, ":exec": true, ":execrows": true, ":execresult": true,
	":copyfrom": true, ":batchexec": true, ":batchmany": true, ":batchone": true,
}

func moduleForSource(source string) string {
	base := path.Base(strings.ReplaceAll(source, "\\", "/"))
	base = strings.TrimSuffix(base, ".sql")
	return base
}

func (g *generator) buildQueries() error {
	qpl := int(*g.opts.QueryParameterLimit)
	for _, q := range g.req.Queries {
		if q.Name == "" || q.Cmd == "" {
			continue
		}
		if q.Cmd == ":execlastid" {
			// As in sqlc's pgx output, only the SQL constant is emitted.
		} else if !validCmds[q.Cmd] {
			return fmt.Errorf("query %s: command %s is not supported by the postgresql engine", q.Name, q.Cmd)
		}
		method := snakeCase(q.Name)
		if !isIdentifier(method) {
			method = sanitize(method)
		}
		if isKeyword(method) || reservedFuncs[method] || strings.HasPrefix(method, "__") {
			method += "_"
		}
		cnst := upperSnake(q.Name)
		cnst = sanitize(cnst)
		if !g.opts.EmitExportedQueries {
			cnst = "_" + cnst
		}
		var comments []string
		for _, c := range q.Comments {
			comments = append(comments, strings.TrimPrefix(c, " "))
		}
		if g.opts.EmitSQLAsComment {
			if len(comments) == 0 {
				comments = append(comments, q.Name)
			}
			comments = append(comments, "")
			for line := range strings.SplitSeq(strings.TrimRight(q.Text, "\n"), "\n") {
				comments = append(comments, "    "+line)
			}
		}
		gq := &Query{
			Cmd:      q.Cmd,
			Name:     q.Name,
			Method:   method,
			Const:    cnst,
			SQL:      q.Text,
			Source:   q.Filename,
			Comments: comments,
			Table:    q.InsertIntoTable,
		}

		params := append([]*plugin.Parameter{}, q.Params...)
		sort.SliceStable(params, func(i, j int) bool { return params[i].Number < params[j].Number })
		if len(params) > 0 {
			fields, order, err := g.paramFields(params)
			if err != nil {
				return fmt.Errorf("query %s: %w", q.Name, err)
			}
			gq.ArgFields = fields
			gq.ArgOrder = order
			if len(params) == 1 && qpl != 0 {
				gq.ArgKind = argSingle
			} else {
				st := &Struct{Name: g.pascal(q.Name) + "Params", Fields: fields}
				gq.ArgStruct = st
				gq.EmitArg = true
				gq.ArgKind = argStruct
				if len(params) <= qpl && q.Cmd != ":copyfrom" && !gq.isBatch() {
					gq.ArgKind = argFields
					gq.EmitArg = false
					gq.ArgStruct = nil
				}
			}
			gq.SQL = rewriteSlices(gq.SQL, params)
		}

		switch q.Cmd {
		case ":one", ":many", ":batchone", ":batchmany":
			if len(q.Columns) == 1 && q.Columns[0].EmbedTable == nil {
				gq.RetKind = retScalar
				gq.RetScalar = g.columnType(q.Columns[0])
			} else {
				gq.RetKind = retStruct
				var reuse *Struct
				for _, s := range g.models {
					if len(s.Fields) != len(q.Columns) {
						continue
					}
					same := true
					for i, f := range s.Fields {
						c := q.Columns[i]
						if c.EmbedTable != nil ||
							f.Name != g.fieldName(columnName(c, i)) ||
							f.Type.key() != g.columnType(c).key() ||
							!sameTable(c.Table, s.Table, g.defaultSchema) {
							same = false
							break
						}
					}
					if same {
						reuse = s
						break
					}
				}
				if reuse != nil {
					gq.RetStruct = reuse
				} else {
					st := g.rowStruct(g.pascal(q.Name)+"Row", q.Columns)
					gq.RetStruct = st
					gq.EmitRet = true
				}
			}
		}
		if q.Cmd == ":copyfrom" {
			if gq.Table == nil || gq.Table.Name == "" {
				return fmt.Errorf("query %s: :copyfrom requires an INSERT INTO statement", q.Name)
			}
			if len(params) == 0 {
				return fmt.Errorf("query %s: :copyfrom requires at least one parameter", q.Name)
			}
			for _, p := range params {
				if p.Column != nil && !g.copyBinarySafe(p.Column) {
					gq.CopyFallback = true
				}
			}
		}
		if gq.isBatch() && len(params) == 0 {
			return fmt.Errorf("query %s: %s requires at least one parameter", q.Name, q.Cmd)
		}
		g.queries = append(g.queries, gq)
	}
	sort.SliceStable(g.queries, func(i, j int) bool { return g.queries[i].Name < g.queries[j].Name })
	return nil
}

// paramFields mirrors sqlc's columnsToStruct: repeated named params share a
// field, repeated unnamed ones get suffixes.
func (g *generator) paramFields(params []*plugin.Parameter) ([]Field, []int, error) {
	var fields []Field
	byName := map[string]int{}
	names := uniquer{}
	seenBase := map[string]int{}
	order := make([]int, 0, len(params))
	for _, p := range params {
		col := p.Column
		if col == nil {
			col = &plugin.Column{}
		}
		raw := paramName(p)
		base := g.fieldName(raw)
		typ := g.columnType(col)
		if idx, ok := byName[base]; ok && col.IsNamedParam {
			f := &fields[idx]
			if f.Type.Elem.Unknown && !typ.Elem.Unknown {
				f.Type = typ
			} else if !typ.Elem.Unknown && !f.Type.Elem.Unknown && f.Type.key() != typ.key() {
				return nil, nil, fmt.Errorf("named param %s has incompatible types: %s, %s", raw, typ.key(), f.Type.key())
			}
			order = append(order, idx)
			continue
		}
		name := base
		jsonName := g.jsonName(raw)
		if n := seenBase[base]; n > 0 {
			name = fmt.Sprintf("%s_%d", base, n+1)
			jsonName = g.jsonName(fmt.Sprintf("%s_%d", raw, n+1))
		}
		seenBase[base]++
		name = names.take(name)
		fields = append(fields, Field{
			Name:     name,
			DBName:   raw,
			JSONName: jsonName,
			Type:     typ,
			Comment:  col.Comment,
			Column:   col,
		})
		if _, ok := byName[base]; !ok {
			byName[base] = len(fields) - 1
		}
		order = append(order, len(fields)-1)
	}
	return fields, order, nil
}

func (g *generator) rowStruct(name string, cols []*plugin.Column) *Struct {
	st := &Struct{Name: name}
	names := uniquer{}
	seenBase := map[string]int{}
	for i, c := range cols {
		raw := columnName(c, i)
		var embed *Struct
		if c.EmbedTable != nil {
			embed = g.findModel(c.EmbedTable)
		}
		var base, jsonRaw string
		var typ fieldType
		if embed != nil {
			base = snakeCase(embed.Name)
			if !isIdentifier(base) || isKeyword(base) {
				base = sanitize(base)
			}
			jsonRaw = base
			typ = fieldType{Elem: &pyType{Expr: "{models}" + embed.Name}, Nullable: false}
		} else {
			base = g.fieldName(raw)
			jsonRaw = raw
			typ = g.columnType(c)
		}
		name := base
		if n := seenBase[base]; n > 0 {
			name = fmt.Sprintf("%s_%d", base, n+1)
			jsonRaw = fmt.Sprintf("%s_%d", jsonRaw, n+1)
		}
		seenBase[base]++
		name = names.take(name)
		st.Fields = append(st.Fields, Field{
			Name:     name,
			DBName:   raw,
			JSONName: g.jsonName(jsonRaw),
			Type:     typ,
			Comment:  c.Comment,
			Column:   c,
			Embed:    embed,
		})
	}
	return st
}

// rewriteSlices rewrites `IN ($n)` / `NOT IN ($n)` for sqlc.slice params to
// `= ANY($n)` / `<> ALL($n)`.
func rewriteSlices(sql string, params []*plugin.Parameter) string {
	for _, p := range params {
		if p.Column == nil || !p.Column.IsSqlcSlice {
			continue
		}
		re := regexp.MustCompile(`(?i)(\bNOT\s+)?\bIN\s*\(\s*\$` + strconv.Itoa(int(p.Number)) + `\s*\)`)
		sql = re.ReplaceAllStringFunc(sql, func(m string) string {
			if strings.HasPrefix(strings.ToUpper(m), "NOT") {
				return fmt.Sprintf("<> ALL($%d)", p.Number)
			}
			return fmt.Sprintf("= ANY($%d)", p.Number)
		})
	}
	return sql
}

// markUsed implements omit_unused_structs.
func (g *generator) markUsed() {
	var markType func(t fieldType)
	var markStruct func(s *Struct)
	markType = func(t fieldType) {
		if t.Elem.Enum != nil {
			t.Elem.Enum.used = true
		}
	}
	markStruct = func(s *Struct) {
		if s == nil {
			return
		}
		s.used = true
		for _, f := range s.Fields {
			markType(f.Type)
			if f.Embed != nil {
				markStruct(f.Embed)
			}
		}
	}
	for _, q := range g.queries {
		for _, f := range q.ArgFields {
			markType(f.Type)
		}
		if q.RetKind == retScalar {
			markType(q.RetScalar)
		}
		markStruct(q.RetStruct)
	}
	if !g.opts.OmitUnusedStructs {
		for _, e := range g.enums {
			e.used = true
		}
		for _, s := range g.models {
			s.used = true
			for _, f := range s.Fields {
				markType(f.Type)
			}
		}
	}
}

func (g *generator) validate() error {
	names := map[string]string{}
	for _, e := range g.enums {
		if !e.used {
			continue
		}
		if prev, ok := names[e.Name]; ok {
			return fmt.Errorf("enum name %s conflicts with %s", e.Name, prev)
		}
		names[e.Name] = "enum " + e.Name
	}
	for _, s := range g.models {
		if !s.used {
			continue
		}
		if prev, ok := names[s.Name]; ok {
			return fmt.Errorf("struct name conflicts with %s: %s", prev, s.Name)
		}
		names[s.Name] = "model " + s.Name
	}
	methods := map[string]string{}
	for _, q := range g.queries {
		if prev, ok := methods[q.Method]; ok {
			return fmt.Errorf("queries %s and %s both map to the Python function name %s", prev, q.Name, q.Method)
		}
		methods[q.Method] = q.Name
	}
	return nil
}

// copyBinarySafe reports whether asyncpg has a binary COPY encoder for col.
func (g *generator) copyBinarySafe(col *plugin.Column) bool {
	name := dataType(col.Type)
	switch strings.TrimPrefix(name, "pg_catalog.") {
	case "money", "citext", "hstore", "ltree", "lquery", "ltxtquery", "tsvector", "tsquery",
		"macaddr", "macaddr8", "vector", "unknown", "any":
		return false
	}
	if builtinType(name) != nil {
		return true
	}
	rel, err := parseIdentifierString(name)
	if err != nil {
		return false
	}
	if rel.Schema == "" {
		rel.Schema = g.defaultSchema
	}
	_, isEnum := g.enumByKey[rel.Schema+"."+rel.Name]
	return isEnum
}
